// Main JavaScript file for Cyberguard theme

const motionEnabled = document.documentElement.classList.contains('motion');

const revealSelector = '.animate-on-scroll, .section-title, .publication-card, .contact-info, .contact-cta, .audit-list, .audit-proof, .view-all-publications';

// Wait for DOM to be fully loaded
document.addEventListener('DOMContentLoaded', function() {
    // Initialize theme toggle
    initThemeToggle();

    // Initialize mobile menu
    initMobileMenu();
    
    // Smooth scrolling for anchor links
    initSmoothScroll();
    
    // Initialize animations
    initAnimations();
    initHeroPhoto();
    initScrollSpy();
    initTagline();
    initAuditRail();
    initCounters();
    initStories();
    
    // Initialize portfolio carousel
    initPortfolioCarousel();

    // Track language switches for analytics
    const langButtons = document.querySelectorAll('.btn-lang');
    langButtons.forEach(button => {
        button.addEventListener('click', function() {
            // Get the language from the URL
            const href = this.getAttribute('href');
            const lang = href.includes('/ru/') ? 'ru' : 'en';
            
            // Set the cookie for future visits
            setLanguagePreference(lang);
        });
    });
});

/**
 * Theme toggle
 */
function initThemeToggle() {
    var btn = document.querySelector('.theme-toggle-btn');
    if (!btn) return;

    btn.addEventListener('click', function() {
        var current = document.documentElement.getAttribute('data-theme');
        var next = current === 'dark' ? 'light' : 'dark';
        document.documentElement.setAttribute('data-theme', next);
        localStorage.setItem('theme', next);
    });

    matchMedia('(prefers-color-scheme:dark)').addEventListener('change', function(e) {
        if (localStorage.getItem('theme')) return;
        document.documentElement.setAttribute('data-theme', e.matches ? 'dark' : 'light');
    });
}

/**
 * Mobile menu initialization
 */
function initMobileMenu() {
    const mobileMenuToggle = document.querySelector('.mobile-menu-toggle');
    
    if (mobileMenuToggle) {
        const setMenuOpen = function(open) {
            document.body.classList.toggle('menu-open', open);
            mobileMenuToggle.setAttribute('aria-expanded', open);
            document.querySelectorAll('main, .site-footer').forEach(region => {
                region.inert = open;
            });
        };

        mobileMenuToggle.addEventListener('click', function() {
            setMenuOpen(!document.body.classList.contains('menu-open'));
        });
        
        // Close menu when clicking outside
        document.addEventListener('click', function(e) {
            if (!e.target.closest('.main-nav') && !e.target.closest('.mobile-menu-toggle') && document.body.classList.contains('menu-open')) {
                setMenuOpen(false);
            }
        });
        
        // Close menu when clicking on navigation links
        const navLinks = document.querySelectorAll('.main-nav a');
        navLinks.forEach(link => {
            link.addEventListener('click', function() {
                setMenuOpen(false);
            });
        });

        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape' && document.body.classList.contains('menu-open')) {
                setMenuOpen(false);
                mobileMenuToggle.focus();
            }
        });

        matchMedia('(min-width: 993px)').addEventListener('change', function(e) {
            if (e.matches) setMenuOpen(false);
        });
    }
}

/**
 * Smooth scrolling for anchor links
 */
function initSmoothScroll() {
    const anchorLinks = document.querySelectorAll('a[href^="#"]:not([href="#"])');
    
    anchorLinks.forEach(link => {
        link.addEventListener('click', function(e) {
            e.preventDefault();
            
            const targetId = this.getAttribute('href');
            const targetElement = document.querySelector(targetId);
            
            if (!targetElement) return;
            
            const headerOffset = document.querySelector('.site-header').offsetHeight;
            const elementPosition = targetElement.getBoundingClientRect().top;
            const offsetPosition = elementPosition + window.pageYOffset - headerOffset;
            
            window.scrollTo({
                top: offsetPosition,
                behavior: motionEnabled ? 'smooth' : 'auto'
            });

            if (!targetElement.hasAttribute('tabindex')) targetElement.setAttribute('tabindex', '-1');
            targetElement.focus({ preventScroll: true });
        });
    });
}

/**
 * Initialize animations for content elements
 */
function initAnimations() {
    if (!motionEnabled) return;

    const animatedElements = document.querySelectorAll(revealSelector);
    
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.15
    };
    
    const observer = new IntersectionObserver((entries, observer) => {
        entries.filter(entry => entry.isIntersecting).forEach((entry, i) => {
            entry.target.style.setProperty('--d', Math.min(i, 5) * 80 + 'ms');
            entry.target.classList.add('animated');
            observer.unobserve(entry.target);
        });
    }, observerOptions);
    
    animatedElements.forEach(element => {
        observer.observe(element);
    });
}

/**
 * Set cookie helper function
 */
function setCookie(name, value, days) {
    let expires = '';
    if (days) {
        const date = new Date();
        date.setTime(date.getTime() + (days * 24 * 60 * 60 * 1000));
        expires = '; expires=' + date.toUTCString();
    }
    document.cookie = name + '=' + value + expires + '; path=/; SameSite=Strict';
}

/**
 * Get cookie helper function
 */
function getCookie(name) {
    const nameEQ = name + '=';
    const ca = document.cookie.split(';');
    for (let i = 0; i < ca.length; i++) {
        let c = ca[i];
        while (c.charAt(0) === ' ') c = c.substring(1, c.length);
        if (c.indexOf(nameEQ) === 0) return c.substring(nameEQ.length, c.length);
    }
    return null;
}

/**
 * Language switcher functions
 */
function setLanguagePreference(lang) {
    setCookie('preferred_lang', lang, 365);
}

/**
 * Initialize portfolio carousel
 */
function initPortfolioCarousel() {
    const portfolioGrid = document.querySelector('.portfolio-grid');
    if (!portfolioGrid) return;
    
    const originalCards = Array.from(portfolioGrid.querySelectorAll('.portfolio-card'));
    if (originalCards.length === 0) return;
    
    var styleEl = null;

    function removeDuplicates() {
        var allCards = portfolioGrid.querySelectorAll('.portfolio-card');
        allCards.forEach(function(card, i) {
            if (i >= originalCards.length) card.remove();
        });
    }

    function checkAndEnableScrolling() {
        portfolioGrid.classList.remove('is-scrolling');
        portfolioGrid.style.animation = 'none';
        removeDuplicates();

        var needsScrolling = portfolioGrid.scrollWidth > portfolioGrid.clientWidth;

        if (needsScrolling && originalCards.length > 1) {
            portfolioGrid.classList.add('is-scrolling');

            var containerWidth = portfolioGrid.parentElement.offsetWidth;
            var gap = parseInt(window.getComputedStyle(portfolioGrid).gap) || 32;
            var estimatedSetWidth = originalCards.length * (320 + gap);

            var setsNeeded = Math.ceil((containerWidth + estimatedSetWidth) / estimatedSetWidth) + 1;
            for (var s = 0; s < setsNeeded; s++) {
                originalCards.forEach(function(card) {
                    var clone = card.cloneNode(true);
                    clone.classList.add('animated');
                    clone.inert = true;
                    portfolioGrid.appendChild(clone);
                });
            }

            var oneSetWidth = portfolioGrid.children[originalCards.length].offsetLeft - portfolioGrid.children[0].offsetLeft;

            if (styleEl) styleEl.remove();
            styleEl = document.createElement('style');
            styleEl.textContent =
                '@keyframes scrollPortfolio{' +
                'from{transform:translate3d(0,0,0)}' +
                'to{transform:translate3d(-' + oneSetWidth + 'px,0,0)}' +
                '}';
            document.head.appendChild(styleEl);

            var speed = 40;
            var duration = oneSetWidth / speed;
            portfolioGrid.style.animation = 'scrollPortfolio ' + duration + 's linear infinite';

            portfolioGrid.addEventListener('mouseenter', pauseAnimation);
            portfolioGrid.addEventListener('mouseleave', resumeAnimation);
            portfolioGrid.addEventListener('focusin', pauseAnimation);
            portfolioGrid.addEventListener('focusout', resumeAnimation);
        } else {
            portfolioGrid.removeEventListener('mouseenter', pauseAnimation);
            portfolioGrid.removeEventListener('mouseleave', resumeAnimation);
            portfolioGrid.removeEventListener('focusin', pauseAnimation);
            portfolioGrid.removeEventListener('focusout', resumeAnimation);
        }
    }
    
    function pauseAnimation() {
        this.style.animationPlayState = 'paused';
    }
    
    function resumeAnimation() {
        this.style.animationPlayState = 'running';
    }
    
    // Initial check
    checkAndEnableScrolling();
    
    // Recheck on window resize
    let resizeTimer;
    window.addEventListener('resize', function() {
        clearTimeout(resizeTimer);
        resizeTimer = setTimeout(checkAndEnableScrolling, 250);
    });
}

/**
 * Hero photo resolves from blur once decoded
 */
function initHeroPhoto() {
    const frame = document.querySelector('.hero-image');
    if (!frame) return;

    const reveal = () => frame.classList.add('is-loaded');
    frame.querySelector('img').decode().then(reveal, reveal);
}

/**
 * Highlight the navigation item of the section in view
 */
function initScrollSpy() {
    const hero = document.querySelector('.hero');
    if (!hero) return;

    const items = new Map();
    document.querySelectorAll('.main-nav li > a').forEach(link => {
        const url = new URL(link.href);
        if (url.pathname !== location.pathname) return;

        const target = url.hash ? document.querySelector(url.hash) : hero;
        if (target) items.set(target, link.parentElement);
    });

    const observer = new IntersectionObserver(entries => {
        entries.filter(entry => entry.isIntersecting).forEach(entry => {
            items.forEach((item, target) => item.classList.toggle('active', target === entry.target));
        });
    }, { rootMargin: '-45% 0px -50% 0px' });

    items.forEach((item, target) => observer.observe(target));
}

/**
 * Run a measurement on animation frames while the element is in view
 */
function onScrollProgress(element, measure) {
    let frame = 0;
    const update = () => {
        frame = 0;
        measure(element.getBoundingClientRect(), window.innerHeight);
    };
    const onScroll = () => {
        if (!frame) frame = requestAnimationFrame(update);
    };

    new IntersectionObserver(entries => {
        if (entries[0].isIntersecting) {
            window.addEventListener('scroll', onScroll, { passive: true });
        } else {
            window.removeEventListener('scroll', onScroll);
        }
        update();
    }).observe(element);
}

function clamp(value, min, max) {
    return Math.min(Math.max(value, min), max);
}

/**
 * Tagline words light up one by one in reading order while scrolling
 */
function initTagline() {
    const tagline = document.querySelector('.tagline');
    if (!tagline || !motionEnabled) return;

    const words = tagline.querySelectorAll('span');
    onScrollProgress(tagline, (rect, viewport) => {
        const progress = clamp((viewport * 0.85 - rect.top) / (rect.height + viewport * 0.35), 0, 1);
        const lit = Math.round(progress * words.length);
        words.forEach((word, i) => word.classList.toggle('is-lit', i < lit));
    });
}

/**
 * Audit process rail fills and reaches each step as it is read
 */
function initAuditRail() {
    const rail = document.querySelector('.audit-steps');
    if (!rail) return;

    const steps = rail.querySelectorAll('.audit-step');
    if (!motionEnabled) {
        steps.forEach(step => step.classList.add('is-reached'));
        return;
    }

    onScrollProgress(rail, (rect, viewport) => {
        const line = viewport * 0.6 - rect.top;
        rail.style.setProperty('--progress', clamp(line / rect.height, 0, 1));
        steps.forEach(step => step.classList.toggle('is-reached', step.offsetTop + 24 <= line));
    });
}

/**
 * Media page stats count up when they come into view
 */
function initCounters() {
    if (!motionEnabled) return;

    const observer = new IntersectionObserver((entries, observer) => {
        entries.filter(entry => entry.isIntersecting).forEach(entry => {
            observer.unobserve(entry.target);
            const value = Number(entry.target.textContent);
            const started = performance.now();
            const step = now => {
                const progress = Math.min((now - started) / 1200, 1);
                entry.target.textContent = Math.round(value * (1 - Math.pow(1 - progress, 3)));
                if (progress < 1) requestAnimationFrame(step);
            };
            requestAnimationFrame(step);
        });
    }, { threshold: 0.5 });

    document.querySelectorAll('.media-stat dd').forEach(counter => {
        const value = Number(counter.textContent);
        if (value > 0 && value < 1000) observer.observe(counter);
    });
}

/**
 * Story loops: each visual acts out what it does while it is in view
 */
function initStories() {
    if (!motionEnabled) return;

    const stories = [
        ['.audit-scan', createScanStory],
        ['.attack-chain', createChainStory],
        ['.certifications-grid', createSpotlightStory]
    ].map(([selector, create]) => {
        const element = document.querySelector(selector);
        return element && Object.assign({ element, visible: false, wait: 1.2 }, create(element));
    }).filter(Boolean);

    if (!stories.length) return;

    let frame = 0;
    let last = 0;
    const tick = now => {
        const dt = last ? Math.min((now - last) / 1000, 0.1) : 0;
        last = now;

        const running = stories.filter(story => story.visible);
        running.forEach(story => {
            if (story.wait > 0) {
                story.wait -= dt;
                return;
            }
            story.time = (story.time + dt) % story.period;
            story.render(story.time);
        });

        frame = running.length ? requestAnimationFrame(tick) : 0;
        if (!frame) last = 0;
    };

    const observer = new IntersectionObserver(entries => {
        entries.forEach(entry => {
            stories.find(story => story.element === entry.target).visible = entry.isIntersecting;
        });
        if (!frame && stories.some(story => story.visible)) frame = requestAnimationFrame(tick);
    }, { threshold: 0.3 });

    stories.forEach(story => observer.observe(story.element));
}

function createScanStory(element) {
    const items = element.querySelectorAll('.scan-item');
    const counter = element.querySelector('.scan-done');
    const fill = element.querySelector('.scan-progress-fill');
    const start = 0.9;
    const step = 0.7;
    const settle = 0.45;
    const rest = start + (items.length - 1) * step + settle;

    return {
        period: rest + 3,
        time: rest,
        render(t) {
            let done = 0;
            items.forEach((item, i) => {
                const at = start + i * step;
                const isDone = t >= at + settle;
                item.classList.toggle('is-active', t >= at && !isDone);
                item.classList.toggle('is-done', isDone);
                if (isDone) done++;
            });
            if (counter.textContent !== String(done)) counter.textContent = done;
            fill.style.transform = 'scaleX(' + done / items.length + ')';
        }
    };
}

function createChainStory(element) {
    const nodes = element.querySelectorAll('.chain-node');
    const links = element.querySelectorAll('.chain-link');
    const finding = element.querySelector('.chain-finding');
    const last = nodes.length - 1;
    const start = 0.3;
    const hop = 0.9;
    const travel = 0.6;
    const reset = start + last * hop + 2.4;

    return {
        period: reset + 1.2,
        time: 0,
        render(t) {
            const on = t < reset;
            nodes.forEach((node, i) => node.classList.toggle('is-lit', on && t >= start + i * hop));
            nodes[last].classList.toggle('is-hit', on && t >= start + last * hop);
            links.forEach((link, i) => {
                const fired = start + i * hop + 0.2;
                link.classList.toggle('is-firing', on && t >= fired);
                link.classList.toggle('is-lit', on && t >= fired + travel);
            });
            finding.classList.toggle('is-on', on && t >= start + last * hop + 0.2);
        }
    };
}

function createSpotlightStory(element) {
    const cards = element.querySelectorAll('.certification-card');
    const beat = 1.8;

    return {
        period: cards.length * beat,
        time: 0,
        render(t) {
            const current = Math.floor(t / beat);
            cards.forEach((card, i) => card.classList.toggle('is-lit', i === current && t - current * beat < beat * 0.75));
        }
    };
}
